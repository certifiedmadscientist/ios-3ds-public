#!/usr/bin/env python3
"""Build boot/ksyms.S: a sorted table of code symbols from KERNEL.BIN (kernel
__TEXT plus the prelinked kexts' __PRELINK,__symtab objects) so the runtime
can print kernel backtraces as name+offset.

Layout: ksym_count (u32), ksym_addr[count] (u32, ascending, Thumb bit
cleared), ksym_name[count] (u32 offsets into ksym_str), ksym_str (NUL-
terminated names, leading '_' dropped)."""
import struct, sys

def macho_syms(d, base):
    """Yield (value, name, type, sect) from the Mach-O at d[base:]."""
    ncmds, = struct.unpack_from('<I', d, base + 16)
    off = base + 28
    for _ in range(ncmds):
        cmd, sz = struct.unpack_from('<II', d, off)
        if cmd == 2:
            symoff, nsyms, stroff, strsize = struct.unpack_from('<IIII', d, off + 8)
            for i in range(nsyms):
                strx, ntype, sect, desc, val = struct.unpack_from(
                    '<IBBhI', d, base + symoff + i * 12)
                end = d.index(b'\0', base + stroff + strx)
                yield val, d[base + stroff + strx:end].decode('latin1'), ntype, sect
        off += sz

def sect_range(d, segname, sectname):
    ncmds, = struct.unpack_from('<I', d, 16)
    off = 28
    for _ in range(ncmds):
        cmd, sz = struct.unpack_from('<II', d, off)
        if cmd == 1:
            nsect, = struct.unpack_from('<I', d, off + 48)
            for s in range(nsect):
                so = off + 56 + s * 68
                sn = d[so:so + 16].split(b'\0')[0].decode()
                sg = d[so + 16:so + 32].split(b'\0')[0].decode()
                addr, size, foff = struct.unpack_from('<III', d, so + 32)
                if sg == segname and sn == sectname:
                    return addr, size, foff
        off += sz
    raise KeyError(segname + sectname)

def main(kernel, out):
    d = open(kernel, 'rb').read()
    ktext = sect_range(d, '__TEXT', '__text')
    ptext = sect_range(d, '__PRELINK', '__text')
    psym = sect_range(d, '__PRELINK', '__symtab')
    def code(v):
        return (ktext[0] <= v < ktext[0] + ktext[1] or
                ptext[0] <= v < ptext[0] + ptext[1])
    syms = {}
    def add(v, n, t):
        if (t & 0xE0) or (t & 0x0E) != 0x0E or not code(v & ~1):
            return                      # stabs / undefined / non-code
        n = n[1:] if n.startswith('_') else n
        syms.setdefault(v & ~1, n)
    for v, n, t, s in macho_syms(d, 0):
        add(v, n, t)
    # concatenated kext symbol objects
    o, end = psym[2], psym[2] + psym[1]
    while o < end:
        o = d.find(b'\xce\xfa\xed\xfe', o, end)
        if o < 0:
            break
        try:
            for v, n, t, s in macho_syms(d, o):
                add(v, n, t)
        except (struct.error, ValueError, IndexError):
            pass
        o += 4
    items = sorted(syms.items())
    strs, offs, pos = [], [], 0
    for a, n in items:
        n = n[:47]
        offs.append(pos)
        strs.append(n)
        pos += len(n) + 1
    with open(out, 'w') as f:
        f.write('/* generated by tools/mk_ksyms.py from %s */\n' % kernel)
        f.write('    .section .rodata.ksyms, "a"\n    .balign 4\n')
        f.write('    .global ksym_count, ksym_addr, ksym_name, ksym_str\n')
        f.write('ksym_count: .word %d\n' % len(items))
        f.write('ksym_addr:\n')
        for i in range(0, len(items), 8):
            f.write('    .word ' + ','.join('0x%08x' % a for a, _ in items[i:i + 8]) + '\n')
        f.write('ksym_name:\n')
        for i in range(0, len(offs), 8):
            f.write('    .word ' + ','.join(str(x) for x in offs[i:i + 8]) + '\n')
        f.write('ksym_str:\n')
        for n in strs:
            f.write('    .asciz "%s"\n' % n.replace('\\', '\\\\').replace('"', '\\"'))
    print('%d symbols, %d string bytes' % (len(items), pos), file=sys.stderr)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
